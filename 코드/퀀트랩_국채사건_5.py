#%% [셀 0] 패키지 + 자료 읽기 =============================================
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

결과폴더 = Path.home() / "Desktop" / "스테이블코인_퀀트랩"
데이터폴더 = 결과폴더 / "데이터"
CSV인코딩 = "utf-8-sig"

설계 = pd.read_csv(데이터폴더 / "국채사건_설계.csv", encoding=CSV인코딩, dtype=str).set_index("항목")["값"]
자료 = pd.read_csv(데이터폴더 / "국채사건_자료_평일.csv", index_col="date", parse_dates=["date"], encoding=CSV인코딩)
강건성4 = pd.read_csv(데이터폴더 / "국채사건_4단계_강건성.csv", encoding=CSV인코딩)
사건창 = pd.read_csv(데이터폴더 / "사건연구_사건창.csv", encoding=CSV인코딩)
추정기간 = pd.read_csv(데이터폴더 / "사건연구_추정기간.csv", encoding=CSV인코딩).set_index("구분")

거래일 = 자료.index
판정사건 = 설계["판정사건"].split(",")                          # A,B,C,E
유의 = float(설계["유의수준"])
열 = "시총_B"                                                  # 유입 (합산 시가총액, $B)

# 추정 기간 하루 변화의 평균·표준편차 (4단계 [셀 0] 과 같음)
주 = 추정기간.loc["주(250일)"]
하루변화 = 자료[열].diff()
추정 = 하루변화.loc[주["시작"]:주["끝"]].dropna()
μ, σ = 추정.mean(), 추정.std(ddof=1)
자유도 = len(추정) - 1


#%% [셀 1] ③ 창 [-1,+1] 을 하루씩 쪼개기 ===================================
def 창(e, 앞, 뒤):
    """묶음 규칙: 첫 0일 + 앞 ~ 마지막 0일 + 뒤 (출처: 퀀트랩_국채사건_4 [셀 1])"""
    k0 = 거래일.get_loc(pd.Timestamp(e["창시작"]))
    k1 = 거래일.get_loc(pd.Timestamp(e["창끝"])) - 1               # 마지막 0일 (주 창이 [0,+1] 이므로)
    return k0 + 앞, k1 + 뒤


행 = []
for _, e in 사건창[사건창["이름"].isin(판정사건)].iterrows():
    i0, i1 = 창(e, -1, 1)                                       # 강건성 ③
    for k in range(i0, i1 + 1):
        행.append({"사건": e["이름"], "방향": int(e["방향"]), "날짜": 거래일[k].date(),
                   "하루변화": 하루변화.iloc[k], "비정상": 하루변화.iloc[k] - μ,
                   "표준편차배수": (하루변화.iloc[k] - μ) / σ})
하루별 = pd.DataFrame(행)

pd.set_option("display.width", 200)
print("[5단계] 강건성 ③ 창 [-1,+1] 의 하루별 비정상 유입 ($B, 방향 곱하기 전)")
print(하루별.to_string(index=False, float_format=lambda v: f"{v:+.3f}"))
가장큰날 = 하루별.loc[(하루별["방향"] * 하루별["비정상"]).idxmax()]
print(f"\n법 진전 방향으로 가장 큰 날: {가장큰날['사건']} {가장큰날['날짜']} "
      f"(비정상 {가장큰날['비정상']:+.2f} $B, 하루 표준편차의 {가장큰날['표준편차배수']:.1f}배)")


#%% [셀 2] 7/16 하루만 빼고 다시 계산 ======================================
뺄날 = pd.Timestamp("2025-07-16").date()                         # 출처: 사용자 확인 (12주차 주간업무보고서, 위 [근거])
assert 가장큰날["날짜"] == 뺄날, "가장 큰 날이 7/16 이 아닙니다 - 자료가 바뀌었는지 확인"


def 판정값(d):
    """사건별 비정상 = 하루 비정상의 합, SE = σ × √창 길이 / S = (방향 × 비정상) 평균, SE = √(SE² 합) ÷ 사건 수
    (퀀트랩_국채사건_4 [셀 1] 과 같은 식)"""
    사건 = d.groupby("사건").agg(방향=("방향", "first"), 비정상=("비정상", "sum"), L=("비정상", "size"))
    S = (사건["방향"] * 사건["비정상"]).mean()
    SE = σ * np.sqrt(사건["L"].sum()) / len(사건)
    t = S / SE
    return {"S": S, "SE": SE, "t": t, "p": 2 * stats.t.sf(abs(t), 자유도), "최소검출효과": 2.8 * SE,
            "5%유의": 2 * stats.t.sf(abs(t), 자유도) < 유의,
            "사건별": ", ".join(f"{n} {v:+.2f}" for n, v in (사건["방향"] * 사건["비정상"]).items())}


결과 = pd.DataFrame([
    {"경우": "③ 창 [-1,+1]", **판정값(하루별)},
    {"경우": "③ 에서 7/16 뺌", **판정값(하루별[하루별["날짜"] != 뺄날])},
])

# ③ 이 4단계와 똑같이 나오는지 확인 (계산 방식이 같다는 점검)
S4 = 강건성4[(강건성4["경우"].str.startswith("③")) & (강건성4["대상"] == "유입")]["S"].iloc[0]
assert np.isclose(결과.loc[0, "S"], S4), "4단계 ③ 유입 S 와 다름"

print("\n[5단계] 7/16 제외 전후 (유입, $B)")
print(결과.to_string(index=False, float_format=lambda v: f"{v:+.3f}"))
print("\n-> 결과를 본 뒤 한 분석이라 판정은 바꾸지 않음 (주 결과: 유입 유의하지 않음)")


#%% [셀 3] 저장 ===========================================================
하루별.to_csv(데이터폴더 / "국채사건_5단계_사후_하루별.csv", index=False, encoding=CSV인코딩)
결과.to_csv(데이터폴더 / "국채사건_5단계_사후_716제외.csv", index=False, encoding=CSV인코딩)
print("저장: 국채사건_5단계_사후_하루별.csv, 국채사건_5단계_사후_716제외.csv")
