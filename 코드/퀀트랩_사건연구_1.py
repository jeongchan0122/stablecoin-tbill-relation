#%% [셀 0] 패키지 + 폴더 + 설계 읽기 ======================================
from pathlib import Path

import numpy as np
import pandas as pd

# 폴더 (출처: 사용자 지시 - 바탕화면/스테이블코인_퀀트랩)
데이터폴더 = Path.home() / "Desktop" / "스테이블코인_퀀트랩" / "데이터"
CSV인코딩 = "utf-8-sig"

# 설계 (출처: 퀀트랩_사건연구_0 - 값은 여기서 읽기만 함)
설계 = pd.read_csv(데이터폴더 / "사건연구_설계.csv", encoding=CSV인코딩, dtype=str).set_index("항목")["값"]
print("설계 항목 수:", len(설계))


#%% [셀 1] CRSP 자료 읽기 + 종목 확인 =====================================
# 종목 일별 (출처: 설계 "종목" 줄들, 수익률 = DlyRet 배당 포함 총수익률)
종목 = pd.read_csv(데이터폴더 / "사건연구_CRSP_일별.csv", parse_dates=["DlyCalDt"])
시장 = pd.read_csv(데이터폴더 / "사건연구_CRSP_시장지수.csv", parse_dates=["dlycaldt"])

# 설계에 적힌 종목 (그룹 4개 + 참고 CRCL + 비트코인 요인 IBIT)
그룹 = {"발행사": 설계["그룹_발행사"].split(","), "거래소": 설계["그룹_거래소"].split(","),
        "은행": 설계["그룹_은행"].split(","), "카드": 설계["그룹_카드"].split(",")}
필요종목 = sum(그룹.values(), []) + [설계["참고종목"], 설계["비트코인요인"]]
있는종목 = set(종목["Ticker"])
빠짐 = [t for t in 필요종목 if t not in 있는종목]
assert not 빠짐, f"CRSP 파일에 없는 종목: {빠짐} -> WRDS 에서 다시 받으세요"

# 한 티커에 PERMNO 가 둘 이상이면 다른 회사가 섞인 것 (티커 재사용 - 확인용)
티커별 = 종목.groupby("Ticker")["PERMNO"].nunique()
assert (티커별 == 1).all(), f"PERMNO 가 둘 이상인 티커: {list(티커별[티커별 > 1].index)}"

# 날짜 × 종목 표 (빈 수익률은 비워 둠 - CRCL 상장 첫날 등)
수익률 = 종목.pivot(index="DlyCalDt", columns="Ticker", values="DlyRet")[필요종목]
수익률["시장"] = 시장.set_index("dlycaldt")["vwretd"]          # 출처: 설계 "시장수익률" (가치가중, 배당 포함)
수익률.index.name = "date"
assert 수익률["시장"].notna().all(), "시장지수가 빈 날이 있습니다 (종목 파일과 날짜가 다름)"

자료기간 = 설계["자료기간"].split(",")
print(f"자료: {수익률.index.min().date()} ~ {수익률.index.max().date()}, 거래일 {len(수익률)}일 "
      f"(설계 자료기간 {자료기간[0]} ~ {자료기간[1]})")
print(수익률.notna().sum().to_string())


#%% [셀 2] 사건 창 다시 만들기 + 설계와 대조 ==============================
# 거래일 달력 = CRSP 에 수익률이 있는 날 (휴장일은 CRSP 에 없음)
거래일 = 수익률.index


def 다음거래일(날, k=1):
    """날 이후 k 번째 거래일 (날이 거래일이 아니면 그 다음 첫 거래일이 1번째)"""
    i = 거래일.searchsorted(날, side="right")
    return 거래일[i + k - 1]


def 영일(날짜, 시각):
    """출처: 설계 "0일규칙" - 장중(9:30~16:00)이면 그날, 장 마감 후면 다음 거래일, 시각 없으면 그날"""
    날 = pd.Timestamp(날짜)
    if 시각:
        시, 분 = map(int, 시각.split(":"))
        if (시, 분) >= (16, 0):                          # 장 마감 후
            return 다음거래일(날)
    return 날 if 날 in 거래일 else 다음거래일(날)       # 장중 또는 시각 없음 (휴일이면 다음 거래일)


원 = pd.DataFrame([r.split(",") for r in 설계["원사건"].split(";")], columns=["번호", "날짜", "시각", "결과"])
원["0일"] = [영일(d, t) for d, t in zip(원["날짜"], 원["시각"])]
창앞, 창뒤 = map(int, 설계["사건창"].split(","))               # 출처: 설계 "사건창" [0, +1]
원["창끝"] = [다음거래일(d, 창뒤) if 창뒤 > 0 else d for d in 원["0일"]]
원 = 원.sort_values("0일").reset_index(drop=True)

# 묶기 (출처: 설계 "묶음규칙" - 창이 겹치면 하나로, 묶은 창 = 첫 0일 ~ 마지막 0일의 다음 거래일)
묶음, 지금 = [], None
for _, r in 원.iterrows():
    if 지금 is not None and r["0일"] <= 지금["창끝"]:
        지금["번호"].append(r["번호"]); 지금["결과"].append(r["결과"]); 지금["창끝"] = max(지금["창끝"], r["창끝"])
    else:
        지금 = {"번호": [r["번호"]], "결과": [r["결과"]], "창시작": r["0일"], "창끝": r["창끝"]}
        묶음.append(지금)

# 설계 "사건목록"과 대조 (이름, 창 시작, 창 끝, 방향)
목록 = pd.DataFrame([r.split(",") for r in 설계["사건목록"].split(";")], columns=["이름", "창시작", "창끝", "방향"])
assert len(목록) == len(묶음), f"묶은 사건 수가 다릅니다: 코드 {len(묶음)} / 설계 {len(목록)}"
행 = []
for (_, s), m in zip(목록.iterrows(), 묶음):
    같음 = pd.Timestamp(s["창시작"]) == m["창시작"] and pd.Timestamp(s["창끝"]) == m["창끝"]
    방향 = -1 if "부결" in m["결과"] else +1                   # 부결 = 법이 막힌 나쁜 소식
    assert 같음 and 방향 == int(s["방향"]), f"사건 {s['이름']} 가 설계와 다릅니다: {m}"
    길이 = int(((거래일 >= m["창시작"]) & (거래일 <= m["창끝"])).sum())
    행.append({"이름": s["이름"], "창시작": m["창시작"].date(), "창끝": m["창끝"].date(),
               "창길이": 길이, "방향": 방향, "원사건": "·".join(m["번호"])})
사건창 = pd.DataFrame(행)
print("사건 창 (설계와 일치):")
print(사건창.to_string(index=False))


#%% [셀 3] 추정 기간 확정 =================================================
# 출처: 설계 "추정기간" - 사건 A 의 0일 11 거래일 전에 끝나는 250 거래일 (MacKinlay 1997 구조)
#       강건성: 같은 끝날, 120 거래일 (설계 "강건성목록")
A0 = pd.Timestamp(사건창.loc[0, "창시작"])
k = 거래일.get_loc(A0)
끝 = k - 11
기간행 = []
for 이름, 일수 in [("주(250일)", 250), ("강건성(120일)", 120)]:
    시작 = 끝 - 일수 + 1
    assert 시작 >= 0, f"{이름}: 자료가 모자랍니다 (자료 시작을 더 앞당겨 받아야 함)"
    기간행.append({"구분": 이름, "시작": 거래일[시작].date(), "끝": 거래일[끝].date(), "일수": 일수})
추정기간 = pd.DataFrame(기간행)

# 추정 기간 안에 사건 창이 없어야 함 (확인용)
for _, e in 사건창.iterrows():
    assert pd.Timestamp(e["창시작"]) > 거래일[끝], "추정 기간과 사건 창이 겹칩니다"
# 추정 기간에 IBIT·종목 수익률이 모두 있어야 함 (CRCL 은 추정 안 함 - 설계 "참고종목방법")
주기간 = 수익률.loc[str(추정기간.loc[0, "시작"]):str(추정기간.loc[0, "끝"])]
빈칸 = 주기간.drop(columns=[설계["참고종목"]]).isna().sum()
assert (빈칸 == 0).all(), f"추정 기간에 빈 수익률: {빈칸[빈칸 > 0].to_dict()}"
print("추정 기간:")
print(추정기간.to_string(index=False))


#%% [셀 4] 그룹 포트폴리오 + 저장 =========================================
# 출처: 설계 "포트폴리오" - 그룹마다 동일가중 (날마다 종목 수익률의 단순 평균)
for 이름, 멤버 in 그룹.items():
    수익률[이름] = 수익률[멤버].mean(axis=1)

수익률.to_csv(데이터폴더 / "사건연구_수익률_일별.csv", encoding=CSV인코딩)
사건창.to_csv(데이터폴더 / "사건연구_사건창.csv", index=False, encoding=CSV인코딩)
추정기간.to_csv(데이터폴더 / "사건연구_추정기간.csv", index=False, encoding=CSV인코딩)
print("그룹:", {k: "+".join(v) for k, v in 그룹.items()})
print("저장: 사건연구_수익률_일별.csv, 사건연구_사건창.csv, 사건연구_추정기간.csv")
