"""
퀀트랩_사건연구_2.py
=====================================================================
[연구] 사건 연구: 미국 스테이블코인법(GENIUS Act)에 대한 주식시장 반응
[단계] 2단계: 검정력 - "반응이 얼마나 커야 이 자료로 잡아낼 수 있는가"

[이 코드가 하는 일]
  사건 창의 수익률은 쓰지 않습니다. 추정 기간(2024-04-24 ~ 2025-04-23) 자료만 씁니다.
  ① 그룹 포트폴리오마다 주 모형(시장 + IBIT)을 추정 기간에 맞춤
  ② 잔차 표준편차(평소 하루 잡음의 크기)로 주판정값의 표준오차를 계산
  ③ 최소 검출 효과 = 2.8 × 표준오차 (5% 양측에서 80% 확률로 잡아낼 수 있는 가장 작은 반응)

[주판정값과 표준오차] (출처: 설계 "주판정값", "검정")
  주판정값 S = (−CAR_A + CAR_B + CAR_C + CAR_D + CAR_E) ÷ 5
  CAR 하나의 표준오차 = σ × √(창 길이)            (MacKinlay 1997)
  다섯 창은 겹치지 않으므로 S 의 표준오차 = σ × √(창 길이 합) ÷ 5
  (추정 계수의 오차에서 오는 작은 부분은 뺀 근사 - 추정 기간 250일에 비해 창이 짧아 영향이 작음, MacKinlay 1997)

[입력] 사건연구_설계.csv, 사건연구_수익률_일별.csv, 사건연구_사건창.csv, 사건연구_추정기간.csv (1단계)
[출력] 사건연구_2단계_검정력.csv
[Spyder] "#%%" 셀 단위로 Shift+Enter
=====================================================================
"""

#%% [셀 0] 패키지 + 자료 읽기 =============================================
from pathlib import Path

import numpy as np
import pandas as pd

데이터폴더 = Path.home() / "Desktop" / "스테이블코인_퀀트랩" / "데이터"
CSV인코딩 = "utf-8-sig"

설계 = pd.read_csv(데이터폴더 / "사건연구_설계.csv", encoding=CSV인코딩, dtype=str).set_index("항목")["값"]
수익률 = pd.read_csv(데이터폴더 / "사건연구_수익률_일별.csv", index_col="date", parse_dates=["date"], encoding=CSV인코딩)
사건창 = pd.read_csv(데이터폴더 / "사건연구_사건창.csv", encoding=CSV인코딩)
추정기간 = pd.read_csv(데이터폴더 / "사건연구_추정기간.csv", encoding=CSV인코딩).set_index("구분")

# 추정 기간만 잘라 씀 (사건 창 수익률은 이 단계에서 쓰지 않음 - 설계 "검정력")
주 = 추정기간.loc["주(250일)"]
추정 = 수익률.loc[주["시작"]:주["끝"]]
assert len(추정) == 주["일수"], "추정 기간 일수가 1단계와 다릅니다"
assert 추정.index.max() < pd.Timestamp(사건창["창시작"].min()), "추정 기간에 사건 창이 섞였습니다"

그룹들 = ["발행사", "거래소", "은행", "카드"]          # 출처: 설계 "그룹_" 줄들 (1단계에서 포트폴리오로 만듦)
비트 = 설계["비트코인요인"]
창길이합 = int(사건창["창길이"].sum())               # A~E 창 길이 합 (1단계: 2+3+2+2+3)
사건수 = len(사건창)
print(f"추정 기간 {주['시작']} ~ {주['끝']} ({len(추정)}일), 사건 {사건수}개, 창 길이 합 {창길이합}일")


#%% [셀 1] 주 모형 맞추기 + 최소 검출 효과 ================================
# 주 모형: R = a + b·R_시장 + c·R_IBIT + e  (출처: 설계 "주모형", 보통최소제곱)
def 모형맞추기(y, X열):
    """추정 기간에 회귀 -> 계수, 잔차 표준편차(자유도 보정), R²"""
    X = np.column_stack([np.ones(len(y))] + [추정[c].to_numpy() for c in X열])
    계수, *_ = np.linalg.lstsq(X, y, rcond=None)
    잔차 = y - X @ 계수
    σ = np.sqrt(잔차 @ 잔차 / (len(y) - X.shape[1]))
    R2 = 1 - 잔차.var() / y.var()
    return 계수, σ, R2


행 = []
for g in 그룹들:
    계수, σ, R2 = 모형맞추기(추정[g].to_numpy(), ["시장", 비트])
    SE = σ * np.sqrt(창길이합) / 사건수                 # 주판정값 S 의 표준오차
    행.append({"그룹": g, "시장베타": 계수[1], "IBIT베타": 계수[2], "R2": R2,
               "잔차SD_일_%": σ * 100, "S_표준오차_%": SE * 100,
               "최소검출효과_%": 2.8 * SE * 100})        # 출처: Bloom (1995), 설계 "검정력"
결과 = pd.DataFrame(행)

pd.set_option("display.width", 200)
print("[2단계] 주판정값(사건 하나당 평균 반응)의 최소 검출 효과 - 주 모형, 추정 기간 250일")
print(결과.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
print("\n읽는 법: 최소검출효과 = 법이 한 걸음 나아갈 때 평균 반응이 이보다 크면 80% 확률로 잡아냄."
      "\n        이보다 작은 반응은 '반응 없음'으로 나와도 '없다'가 아니라 '판단 불가'.")


#%% [셀 2] 저장 ===========================================================
결과.to_csv(데이터폴더 / "사건연구_2단계_검정력.csv", index=False, encoding=CSV인코딩)
print("저장: 사건연구_2단계_검정력.csv")
