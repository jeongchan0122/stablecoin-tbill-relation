# F 통계량: 관련이 확실한가 (도구변수가 약하지 않은가)
# F는 "GIV와 Flow의 관계가 우연이 아니라고 얼마나 자신 있게 말할 수 있나"를 잽니다. 설명변수가 하나라서 F = (계수 ÷ 표준오차)², 즉 t값의 제곱입니다.

# 도구변수가 주는 의의- 한마디로 "스테이블코인 유입이 금리를 내린다"는 인과관계를 주장할 수 있게 해주는 장치
# 1. 풀어야 할 문제: 유입과 금리는 서로 얽혀 있다
# 논문이 알고 싶은 건 "스테이블코인에 돈이 들어오면 발행사가 T-bill을 사서 3개월 금리가 내려가는가"입니다. 그런데 유입과 금리를 그냥 회귀하면 두 가지 문제가 생깁니다(2.3절, 부록 A).
# 역인과: 금리가 오르면 이자가 없는 스테이블코인을 들고 있는 비용이 커져 유입이 줄어듭니다. 금리가 유입에 영향을 주는 방향도 있는 것입니다.
# 누락변수: 위험선호가 커지는 시기에는 암호화폐로 돈이 몰리는 동시에 안전자산 금리도 움직입니다. 제3의 요인이 둘을 함께 움직이는 경우입니다.
# 여담, 그래서 단순 회귀를 하면 $3.5B 유입에 금리가 30일간 약 21bp 내려간다는, 연준 금리인하급의 말이 안 되는 숫자가 나옵니다(부록 A).

# 2. 해법: 금리와 무관한 이유로 생긴 유입만 골라내기
# 도구변수의 조건은 두 가지입니다.
# 관련성: 유입을 실제로 움직여야 합니다. → F 통계량으로 확인
# 배제 조건: 금리에는 유입을 통해서만 영향을 줘야 합니다. 거시 여건이나 위험선호와는 무관해야 합니다. (아직 코딩으로 안다룸)

# 3. GIV의 아이디어: 시장이 몇 개 페어에 쏠려 있다는 점을 이용
