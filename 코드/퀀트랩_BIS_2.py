#%% [셀 3] 함수: 윈저화 / GIV_t / 5일 합 / 1단계 회귀 ======================
# 계산은 하지 않고 함수 네 개만 정의하는 셀
# 성장률 g → ① 윈저화 → ② GIV_t (일별) → ③ GIV(5d) (5일 합) → ④ 1단계 회귀
def 윈저화(g, 활성, 범위, 중심, 대상, MAD기준="중앙값"):
    """
    튀는 성장률을 잘라냅니다
    성장률 g 를 [중심 − 8×1.4826×MAD, 중심 + 8×1.4826×MAD] 로 자름
    출처: 각주 18 "Growth rates are robust-winsorized at ±8 × 1.4826 × MAD"

    ── 아래 네 가지는 논문에 명시 없음 → 모든 경우 계산 (출처: 사용자 지시)
       최종: 저자 답신으로 확정 - 범위 "전체", 중심 "0", MAD기준 "중앙값", 대상 "활성" ([셀 6])
    범위 : "날짜별" = 그날의 페어들로 MAD 계산 / "페어별" = 그 페어의 전 기간으로
           / "전체" = 모든 날짜·페어를 한꺼번에
    중심 : "중앙값" = 그 범위의 중앙값 / "0"
    MAD기준 : MAD 를 무엇에서 잰 거리로 구하나
           "중앙값" = median(|x − 중앙값|)  (중앙값 절대편차의 표준 정의)
           "0"     = median(|x − 0|)
           중심이 "중앙값"이면 MAD기준도 "중앙값"만 씀
           (출처: 사용자 지시 - 중심이 0일 때만 MAD기준을 둘로 나눠 윈저화 18가지)
    대상 : "활성"  = 활성 페어의 성장률만으로 중앙값·MAD 계산
           / "전체" = 성장률이 정의되는 모든 패널 페어(226개)로 계산
           (자르기 자체는 모든 값에 적용. GIV에는 어차피 활성 페어만 들어감)
    """
    기준값 = g.where(활성) if 대상 == "활성" else g
    x = 기준값.values

    # 활성 페어가 하나도 없는 날(예: 표본 첫날)은 중앙값을 구할 값이 없어서
    # "All-NaN slice" 경고가 뜸. 결과는 빈 값이 되고 GIV도 N_t<5 로 어차피 정의 안 됨 -> 경고만 숨김
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=RuntimeWarning)
        if 범위 == "날짜별":
            축 = dict(axis=1, keepdims=True)
        elif 범위 == "페어별":
            축 = dict(axis=0, keepdims=True)
        else:  # 전체
            축 = dict()
        med = np.nanmedian(x, **축)
        거리기준 = med if MAD기준 == "중앙값" else 0.0
        mad = np.nanmedian(np.abs(x - 거리기준), **축)

    c = med if 중심 == "중앙값" else 0.0
    하한, 상한 = c - 윈저배수 * mad, c + 윈저배수 * mad
    return pd.DataFrame(np.clip(g.values, 하한, 상한), index=g.index, columns=g.columns)


def GIV_일별(g, 활성, 전날):
    """
    출처: 논문 2.3절 식 (2)
      s_i,t−1 : 전날 시가총액 점유율
      ḡ_t     = Σ_i s_i,t−1 g_i,t          (규모가중 평균 성장률)
      ε_i,t   = g_i,t − ḡ_t                (개별 충격)
      GIV_t   = Σ_i (s_i,t−1 − 1/N_t) ε_i,t
      N_t     : t−1 활성 페어 수 (출처: 저자 답신)
      N_t < 5 이면 GIV_t 정의 안 함 (출처: 각주 18)
[저자 답신에 명시 없음] "N_t ≥ 5" 를 t−1 활성 N 과 양일 활성 수 중 어디에 적용하는지
  -> 1/N 과 같은 N(t−1 활성)에 적용. 표본 기간 활성 페어 최솟값이 12 라 어느 쪽이든 결과 같음

      점유율 s 의 분모 = 그날 t−1·t 모두 활성인 페어들의 전날 시총 합
      [논문·저자 답신에 직접 명시 없음] 다만 1장·2.3절은 GIV가 "by construction, orthogonal to
      any common factor" 라고 함. 모든 페어의 성장률에 공통 충격 c 가 더해지면
      ḡ 는 c × Σs 만큼, ε = g − ḡ 는 c × (1 − Σs) 만큼 바뀜. ε 에서 c 가 사라지려면
      성장률이 있는 페어(양일 활성) 위에서 Σs = 1 이어야 하므로, 이 분모가 위 성질과 맞는 정의
      (가중치 합 Σ(s − 1/N) = 0 은 필요 조건이 아님. 저자 답신의 N 정의에서는 0 이 아닐 수 있음)
    """
    s = 전날.where(활성)
    s = s.div(s.sum(axis=1), axis=0)
    gg = g.where(활성)
    N = (전날 > 활성기준).sum(axis=1)   # 출처: 저자 답신 - 1/N의 N은 t−1 활성만으로 셈
                                    # (성장률 표본은 그대로 t−1·t 모두 활성, 각주 18)

    g_bar = (s * gg).sum(axis=1)
    eps = gg.sub(g_bar, axis=0)
    giv = ((s.sub(1 / N, axis=0)) * eps).sum(axis=1)
    giv[N < 최소N] = np.nan
    return giv


def 오일합(giv, 방식):
    """
    GIV(5d)_t = 5일 합 (출처: 논문 2.3절 "GIV(5d)_t = Σ_{s=0}^{4} GIV_{t−s},
                which aligns with our 5-day flow measure")
    창 안에 빈 값이 하나라도 있으면 합도 빈 값 (정의되지 않은 값의 합은 정의 불가)
    방식 (출처: 사용자 지시 - 4가지 모두 실험):
  최종: "가-3" (출처: 저자 답신 - GIV(5일)는 최근 달력일 5개(t−4 ~ t)의 합)
      "나"   : giv 는 평일 표로 계산된 것 → 평일 5개 합
      "가-1" : 달력일 giv 에서 평일만 뽑아 → 평일 5개 합
      "가-2" : 달력일 giv 를 (5 거래일 전, 오늘] 기간 전부 합 → Flow(5d)와 같은 기간
      "가-3" : 달력일 giv 를 달력일 5개 합 → 평일만 뽑음
    """
    if 방식 in ("나", "가-1"):
        return giv.reindex(평일).rolling(5).sum()
    if 방식 == "가-3":
        return giv.rolling(5).sum().reindex(평일)
    # 가-2
    결과 = pd.Series(np.nan, index=평일)
    for k in range(5, len(평일)):
        창 = giv.loc[(giv.index > 평일[k - 5]) & (giv.index <= 평일[k])]
        if 창.notna().all() and len(창) > 0:
            결과.iloc[k] = 창.sum()
    return 결과


def 일단계회귀(giv5):
    """
    Flow(5d)_t = 상수 + 계수 × GIV(5d)_t + 오차
    출처: 논문 표 2 - 종속변수 5일 Flow($B), 설명변수 GIV(5d), 상수항
    출처: 표 2 주석 "Newey-West standard errors with one lag ... HAC-robust F-statistic"
    F = (계수 / HAC 표준오차)²  : 설명변수 1개일 때 HAC Wald F 의 정의
    1SD당 유입 = 계수 × GIV(5d) 표준편차  (출처: 표 2 "5-day flow per 1 SD of GIV ($B)")
    [논문에 명시 없음] Newey-West 의 소표본 보정 여부 -> statsmodels 기본값 = 보정 안 함, 보정하면 F가 약 0.15% 작아짐
      (보정 계수 n/(n−2) ≈ 1.0015 수준이라 F 에 주는 영향은 0.1% 안팎)
      소표본 보정은 표준오차를 계산할 때 표본이 유한하다는 점을 감안해 살짝 키워주는 조정
      회귀의 오차는 직접 볼 수 없어서 잔차(실제값 − 추정값)로 대신 추정합니다. 
      그런데 잔차는 추정한 직선에 맞춰진 값이라, 진짜 오차보다 약간 작게 나오는 경향이 있습니다. 그래서 분산에 n/(n−k)를 곱해 보정하기도 합니다.
      논문에 없는 이유와 우리 선택
      통계 프로그램마다 기본값이 다릅니다. Stata의 newey는 보정을 하고, R의 sandwich와 파이썬의 statsmodels는 기본적으로 하지 않습니다. 
      논문은 어떤 프로그램을 썼는지 밝히지 않아서 어느 쪽인지 알 수 없습니다.
    """
    자료 = pd.concat([Flow5, giv5.rename("GIV")], axis=1).dropna()
    X = sm.add_constant(자료["GIV"])
    r = sm.OLS(자료["Flow5"], X).fit(cov_type="HAC", cov_kwds={"maxlags": 1})
    # [논문에 명시 없음] 1SD당 유입의 표준편차를 어느 표본으로 구하나
    #   회귀표본 = 회귀에 실제로 들어간 1,362일 / 전체표본 = 평일 1,367일 중 GIV(5d)가 있는 날
    #   -> 두 값 모두 계산해서 [셀 4]에서 각각 비교 (출처: 사용자 지시)
    return {
        "계수": r.params["GIV"], "표준오차": r.bse["GIV"], "상수": r.params["const"],
        "관측치": int(r.nobs), "F": r.tvalues["GIV"] ** 2, "R2": r.rsquared,
        "1SD당유입_회귀표본": r.params["GIV"] * 자료["GIV"].std(),
        "1SD당유입_전체표본": r.params["GIV"] * giv5.reindex(평일).std(),
    }


