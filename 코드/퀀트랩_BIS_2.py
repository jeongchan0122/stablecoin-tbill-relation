def 성장률과_활성(시총표):
    """
    g_i,t  : 시가총액 성장률, 퍼센트포인트
             출처: 논문 2.3절 "let g_i,t denote the growth rate of market capitalization"
             출처: 표 2 주석 "The granular IV is expressed in percentage-point units"
             [논문에 명시 없음] 성장률 공식. "growth rate"의 문자 그대로의 뜻인
                 (MC_t − MC_{t−1}) / MC_{t−1} × 100 을 사용 (로그 성장률 아님)
             전날 값이 0 이하이면 나눗셈이 정의되지 않으므로 빈 값 (수학적으로 불가피)
    활성   : t−1 과 t 모두 $1M 초과 (출처: 각주 18)
    """
    전날 = 시총표.shift(1)
    g = (시총표 - 전날) / 전날.where(전날 > 0) * 100
    활성 = (시총표 > 활성기준) & (전날 > 활성기준)
    return g, 활성, 전날
 
 
