# -*- coding: utf-8 -*-
"""
퀀트랩_국채사건_2.py
=====================================================================
[연구] 국채 사건 연구: GENIUS Act 에 단기국채 스프레드와 스테이블코인 유입이 어떻게 반응했는가
[단계] 2단계: 검정력 - "반응이 얼마나 커야 이 자료로 잡아낼 수 있는가"

[이 코드가 하는 일]
  사건 창의 값은 쓰지 않습니다. 추정 기간(2024-04-24 ~ 2025-04-23) 자료만 씁니다.
  ① 스프레드(bp)와 합산 시가총액($B)의 하루 변화를 구해 평균과 표준편차를 계산
  ② 판정값 S 의 표준오차 = σ × √(판정 사건 창 길이 합) ÷ 판정 사건 수
  ③ 최소 검출 효과 = 2.8 × 표준오차 (5% 양측에서 80% 확률로 잡아낼 수 있는 가장 작은 반응)

[근거]
  평균 조정 모형과 CAR 표준오차: MacKinlay (1997) / 최소 검출 효과: Bloom (1995)
  판정 사건 = A, B, C, E (설계 "판정사건" - D 는 FOMC 와 겹쳐 뺌)
  하루 변화끼리 독립이라고 보는 근사 (설계 "검정")

[입력] 국채사건_설계.csv, 국채사건_자료_평일.csv (1단계), 사건연구_사건창.csv, 사건연구_추정기간.csv
[출력] 국채사건_2단계_검정력.csv
[Spyder] "#%%" 셀 단위로 Shift+Enter
=====================================================================
"""

#%% [셀 0] 패키지 + 자료 읽기 =============================================
from pathlib import Path

import numpy as np
import pandas as pd

데이터폴더 = Path.home() / "Desktop" / "스테이블코인_퀀트랩" / "데이터"
CSV인코딩 = "utf-8-sig"

설계 = pd.read_csv(데이터폴더 / "국채사건_설계.csv", encoding=CSV인코딩, dtype=str).set_index("항목")["값"]
자료 = pd.read_csv(데이터폴더 / "국채사건_자료_평일.csv", index_col="date", parse_dates=["date"], encoding=CSV인코딩)
사건창 = pd.read_csv(데이터폴더 / "사건연구_사건창.csv", encoding=CSV인코딩)
추정기간 = pd.read_csv(데이터폴더 / "사건연구_추정기간.csv", encoding=CSV인코딩).set_index("구분")

판정사건 = 설계["판정사건"].split(",")                        # A,B,C,E
판정창 = 사건창[사건창["이름"].isin(판정사건)]
창길이합 = int(판정창["창길이"].sum())                        # 국채 거래일 기준 (1단계에서 주식 창과 같음을 확인)
사건수 = len(판정창)

# 하루 변화 (평일 자료에서 전 평일 대비)
변화 = 자료[["스프레드_bp", "시총_B", "3개월_bp"]].diff()
주 = 추정기간.loc["주(250일)"]
추정 = 변화.loc[주["시작"]:주["끝"]].dropna()
assert 추정.index.max() < pd.Timestamp(사건창["창시작"].min()), "추정 기간에 사건 창이 섞였습니다"
print(f"추정 기간 {주['시작']} ~ {주['끝']}: 하루 변화 {len(추정)}개, 판정 사건 {판정사건}, 창 길이 합 {창길이합}일")


#%% [셀 1] 최소 검출 효과 ==================================================
행 = []
for 열, 이름, 단위 in [("스프레드_bp", "스프레드", "bp"), ("시총_B", "유입", "$B"), ("3개월_bp", "3개월 금리(강건성)", "bp")]:
    μ, σ = 추정[열].mean(), 추정[열].std(ddof=1)
    SE = σ * np.sqrt(창길이합) / 사건수                          # 판정값 S 의 표준오차
    행.append({"대상": 이름, "단위": 단위, "하루평균변화": μ, "하루변화SD": σ,
               "S_표준오차": SE, "최소검출효과": 2.8 * SE})      # 출처: Bloom (1995), 설계 "검정력"
결과 = pd.DataFrame(행)

pd.set_option("display.width", 200)
print("[2단계] 판정값 S(사건당 평균 반응)의 최소 검출 효과 - 추정 기간 자료만 사용")
print(결과.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
print("\n읽는 법: 법이 한 걸음 나아갈 때 평균 반응이 최소검출효과보다 크면 80% 확률로 잡아냄."
      "\n        하루평균변화는 '평소에도 늘던 몫' - 3단계에서 창 길이만큼 빼고 봄 (설계 '평균조정')")


#%% [셀 2] 저장 ===========================================================
결과.to_csv(데이터폴더 / "국채사건_2단계_검정력.csv", index=False, encoding=CSV인코딩)
print("저장: 국채사건_2단계_검정력.csv")
