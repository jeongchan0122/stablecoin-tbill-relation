"""
퀀트랩_유입베타_2.py
=====================================================================
[연구] 유입 베타 연구: 사건 전 '스테이블코인 유입과 같이 움직이던 정도'로 고른 주식이
       GENIUS Act 소식에 더 크게 반응했는가
[단계] 2단계: 유입 베타 + 5개 묶음 + 검정력

[이 코드가 하는 일]
  사건 창의 수익률은 아직 보지 않습니다. 추정 기간(2024-04-24 ~ 2025-04-23) 자료만 씁니다.
  ① 종목마다 R = a + b·시장 + c·IBIT + d·유입 회귀 -> 유입 베타 d (설계 "베타모형")
  ② 유입 베타 순서로 5개 묶음 (설계 "묶음") - 묶음별 종목 수·평균 베타·업종, 3부 종목의 위치 출력
  ③ 묶음별 동일가중 일별 수익률 + 차이묶음(묶음5 − 묶음1) 만들기 (설계 "묶음가중", "차이묶음")
  ④ 차이묶음에 3부 모형(시장 + IBIT)을 추정 기간에 맞춰 잔차 표준편차 -> S_차이 의 최소 검출 효과

[근거]
  회귀·잔차 표준편차(자유도 보정): 퀀트랩_사건연구_2 와 같은 계산 (MacKinlay 1997)
  S 의 표준오차 = σ × √(판정 사건 창 길이 합) ÷ 판정 사건 수 / 최소 검출 효과 = 2.8 × 표준오차 (Bloom 1995)

[입력] 유입베타_설계.csv, 유입베타_수익률_일별.csv, 유입베타_요인_일별.csv, 유입베타_종목목록.csv (1단계),
       사건연구_추정기간.csv, 사건연구_사건창.csv (3부)
[출력] 유입베타_2단계_베타.csv         (종목별 유입 베타·t값·묶음)
       유입베타_묶음수익률_일별.csv    (날짜 × 묶음1~5·차이 - CRSP 에서 나온 값이라 공유·업로드 금지)
       유입베타_2단계_검정력.csv
[Spyder] "#%%" 셀 단위로 Shift+Enter
=====================================================================
"""

#%% [셀 0] 패키지 + 자료 읽기 =============================================
from pathlib import Path

import numpy as np
import pandas as pd

데이터폴더 = Path.home() / "Desktop" / "스테이블코인_퀀트랩" / "데이터"
CSV인코딩 = "utf-8-sig"

설계 = pd.read_csv(데이터폴더 / "유입베타_설계.csv", encoding=CSV인코딩, dtype=str).set_index("항목")["값"]
수익률 = pd.read_csv(데이터폴더 / "유입베타_수익률_일별.csv", index_col="date", parse_dates=["date"], encoding=CSV인코딩)
요인 = pd.read_csv(데이터폴더 / "유입베타_요인_일별.csv", index_col="date", parse_dates=["date"], encoding=CSV인코딩)
목록 = pd.read_csv(데이터폴더 / "유입베타_종목목록.csv", index_col="PERMNO", encoding=CSV인코딩, dtype={"SICCD": str})
추정기간 = pd.read_csv(데이터폴더 / "사건연구_추정기간.csv", encoding=CSV인코딩).set_index("구분")
사건창 = pd.read_csv(데이터폴더 / "사건연구_사건창.csv", encoding=CSV인코딩)
목록.index = 목록.index.astype(str)                 # 수익률 파일의 열 이름(PERMNO)과 같은 글자로 맞춤

주 = 추정기간.loc["주(250일)"]
추정 = slice(주["시작"], 주["끝"])
assert pd.Timestamp(주["끝"]) < pd.Timestamp(사건창["창시작"].min()), "추정 기간에 사건 창이 섞였습니다"
print(f"추정 기간 {주['시작']} ~ {주['끝']}, 종목 {수익률.shape[1]:,}개")


#%% [셀 1] 종목별 유입 베타 ===============================================
# 출처: 설계 "베타모형" - R_i = a + b·R_시장 + c·R_IBIT + d·유입 + e (보통최소제곱, 일별), 유입 베타 = d
X전체 = 요인.loc[추정, ["시장", "IBIT", "유입_B"]]
X전체.insert(0, "상수", 1.0)
행 = []
for p in 수익률.columns:
    y = 수익률.loc[추정, p]
    있음 = y.notna().to_numpy()
    X, yv = X전체.to_numpy()[있음], y.to_numpy()[있음]
    계수, *_ = np.linalg.lstsq(X, yv, rcond=None)
    잔차 = yv - X @ 계수
    자유도 = len(yv) - X.shape[1]
    σ2 = 잔차 @ 잔차 / 자유도
    SE = np.sqrt(σ2 * np.diag(np.linalg.inv(X.T @ X)))       # 계수의 표준오차 (보통최소제곱)
    행.append({"PERMNO": p, "일수": len(yv), "유입베타": 계수[3], "유입베타_t": 계수[3] / SE[3],
               "시장베타": 계수[1], "IBIT베타": 계수[2]})
베타 = pd.DataFrame(행).set_index("PERMNO")
assert (베타["일수"] >= int(설계["자료충분"])).all(), "200일 미만 종목이 섞였습니다 (1단계 확인)"
# 유입베타 단위: 유입이 하루 10억 달러($1B) 늘 때 그 종목 수익률이 몇 만큼 더 움직이나 (수익률은 소수, 0.01 = 1%)
print("[유입 베타 분포] (단위: 유입 $1B 당 수익률, 0.001 = 0.1%p)")
print(베타["유입베타"].describe().to_string(float_format=lambda v: f"{v:.5f}"))
print(f"  유입베타 t 가 |2| 넘는 종목 비율: {(베타['유입베타_t'].abs() > 2).mean():.1%} "
      f"(우연이면 약 5% - 종목 하나의 베타는 잡음이 크다는 뜻, 그래서 묶음으로 봄)")


#%% [셀 2] 5개 묶음 ========================================================
# 출처: 설계 "묶음" - 유입 베타 순서로 5개 (1 = 가장 작음, 5 = 가장 큼), 사건 기간 내내 고정
베타["묶음"] = pd.qcut(베타["유입베타"], 5, labels=[1, 2, 3, 4, 5]).astype(int)
베타 = 베타.join(목록[["Ticker", "IssuerNm", "SICCD", "PrimaryExch"]])

요약 = 베타.groupby("묶음").agg(종목수=("유입베타", "size"), 평균유입베타=("유입베타", "mean"),
                                최소=("유입베타", "min"), 최대=("유입베타", "max"),
                                평균IBIT베타=("IBIT베타", "mean"), 평균시장베타=("시장베타", "mean"))
print("[묶음별 요약]")
print(요약.to_string(float_format=lambda v: f"{v:.4f}"))

# 업종 (SIC 앞 두 자리) - 묶음마다 가장 많은 업종 3개 (이름은 붙이지 않고 코드만)
베타["SIC2"] = 베타["SICCD"].astype(str).str.zfill(4).str[:2]
print("\n[묶음별 많은 업종 (SIC 앞 두 자리: 종목 수)]")
for g, d in 베타.groupby("묶음"):
    print(f"  묶음{g}: {d['SIC2'].value_counts().head(3).to_dict()}")

# 3부 종목의 위치 (출처: 퀀트랩_사건연구_0 종목 - KBE·KRE 는 ETF 라 이번 표본에 없음)
print("\n[3부 종목의 묶음] (3부 결과를 알고 보는 참고. 판정에 쓰지 않음)")
for t in ["COIN", "PYPL", "V", "MA"]:
    r = 베타[베타["Ticker"] == t]
    print(f"  {t}: " + (f"묶음 {int(r['묶음'].iloc[0])}, 유입베타 {r['유입베타'].iloc[0]:.5f} (t {r['유입베타_t'].iloc[0]:+.2f})"
                         if len(r) else "표본에 없음"))


#%% [셀 3] 묶음 수익률 + 검정력 ============================================
# 출처: 설계 "묶음가중" (동일가중, 그날 수익률 있는 종목의 평균), "차이묶음" (묶음5 − 묶음1)
묶음수익률 = pd.DataFrame({f"묶음{g}": 수익률[베타.index[베타["묶음"] == g]].mean(axis=1) for g in range(1, 6)})
묶음수익률["차이"] = 묶음수익률["묶음5"] - 묶음수익률["묶음1"]
assert 묶음수익률.loc[pd.Timestamp(주["시작"]):pd.Timestamp(사건창["창끝"].max())].notna().all().all(), "묶음 수익률이 빈 날이 있습니다"

# 3부 모형(시장 + IBIT)을 추정 기간에 맞춤 -> 잔차 표준편차 (설계 "비정상수익률모형", 퀀트랩_사건연구_2 와 같은 계산)
판정사건 = 설계["판정사건"].split(",")
판정창 = 사건창[사건창["이름"].isin(판정사건)]
창길이합, 사건수 = int(판정창["창길이"].sum()), len(판정창)
X = 요인.loc[추정, ["시장", "IBIT"]].assign(상수=1.0)[["상수", "시장", "IBIT"]].to_numpy()
행 = []
for g in 묶음수익률.columns:
    y = 묶음수익률.loc[추정, g].to_numpy()
    계수, *_ = np.linalg.lstsq(X, y, rcond=None)
    잔차 = y - X @ 계수
    σ = np.sqrt(잔차 @ 잔차 / (len(y) - X.shape[1]))
    SE = σ * np.sqrt(창길이합) / 사건수                     # S 의 표준오차
    행.append({"묶음": g, "잔차SD_일_%": σ * 100, "S_표준오차_%": SE * 100,
               "최소검출효과_%": 2.8 * SE * 100, "R2": 1 - 잔차.var() / y.var()})
검정력 = pd.DataFrame(행)
print(f"\n[검정력] 판정 사건 {판정사건}, 창 길이 합 {창길이합}일 - 추정 기간 자료만 사용")
print(검정력.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
print("\n읽는 법: '차이' 줄의 최소검출효과 = 법이 한 걸음 나아갈 때 묶음5 가 묶음1 보다 이만큼(사건당 평균) 더 올라야"
      "\n        80% 확률로 잡아냄. 이보다 작은 차이는 '판단 불가'로 남을 가능성이 큼")


#%% [셀 4] 저장 ============================================================
베타.to_csv(데이터폴더 / "유입베타_2단계_베타.csv", encoding=CSV인코딩)
묶음수익률.to_csv(데이터폴더 / "유입베타_묶음수익률_일별.csv", encoding=CSV인코딩)
검정력.to_csv(데이터폴더 / "유입베타_2단계_검정력.csv", index=False, encoding=CSV인코딩)
print("저장: 유입베타_2단계_베타.csv, 유입베타_묶음수익률_일별.csv, 유입베타_2단계_검정력.csv")
print("      (베타·묶음수익률 파일은 CRSP 에서 나온 값 - 공유·업로드 금지)")
