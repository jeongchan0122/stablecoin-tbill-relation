# 입력: 퀀트랩_거래전략_5 [셀 3] 이 저장한 거래전략_5단계_거래.csv (읽기만 함)
# 비교: ① 신호대로 갈아타기 (설계 "전략규칙")  ② 신호 무관 매일 갈아타기 (5단계 [셀 4] 참고와 같은 비교)
# 지표 (결정한 날마다의 13일 초과수익, 늘 6개월물 대비, bp)
#   평균, 표준편차, 손실 비율, 정보비율 = 평균 ÷ 표준편차 × √(252 ÷ 13)  (13일 수익을 1년 기준으로 환산한 근사)
#   비용 전 / 비용 후(문헌값 3개월 0.74, 6개월 0.79 bp, 설계 "거래비용_문헌값")
from pathlib import Path
import re
import numpy as np, pandas as pd

D = Path.home() / "Desktop" / "스테이블코인_퀀트랩" / "데이터"
E = "utf-8-sig"
설계 = pd.read_csv(D / "거래전략_설계.csv", encoding=E, dtype=str).set_index("항목")["값"]
s3, s6 = [float(v) for v in re.findall(r"\d+\.\d+", 설계["거래비용_문헌값"])][:2]
주h = int(설계["주h"])
거 = pd.read_csv(D / "거래전략_5단계_거래.csv", encoding=E, index_col=0, parse_dates=True)
거["금리빔"] = 거["금리빔"].astype(str) == "True"
거["갈아탐"] = 거["갈아탐"].astype(str) == "True"
비용 = s3 * 거["비용계수3"] + s6 * 거["비용계수6"]                     # 한 번 갈아탈 때 비용 (bp)
유효 = ~거["금리빔"]                                                   # 금리가 있어 거래 가능한 날

전략 = {"① 신호대로": 거["갈아탐"], "② 매일 갈아탐": 유효}
행 = []
for 이름, 갈 in 전략.items():
    for 구분, x in [("비용 전", np.where(갈, 거["초과_bp"], 0.0)),
                   ("비용 후", np.where(갈, 거["초과_bp"] - 비용, 0.0))]:
        x = pd.Series(x, index=거.index)[유효]
        평균, 표준편차 = x.mean(), x.std()
        행.append({"전략": 이름, "구분": 구분, "갈아탄 날": int(갈.sum()), "평균(bp)": 평균, "표준편차(bp)": 표준편차,
                  "손실 비율": (x[갈[유효]] < 0).mean(),
                  "정보비율(연)": 평균 / 표준편차 * np.sqrt(252 / 주h) if 표준편차 > 0 else np.nan})
표 = pd.DataFrame(행)
pd.set_option("display.width", 200)
print("[사후 추가 - 위험 조정 비교] 결정한 날마다의 13일 초과수익 (늘 6개월물 대비), 판정에 안 씀")
print(표.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
print("\n읽는 법: 정보비율 = 위험(표준편차) 1 당 초과수익. ① 이 ② 보다 뚜렷이 높아야 신호가 위험 대비로도 도움이 된 것")
print("        손실 비율 = 갈아탄 날 중 6개월물보다 못했던 날의 비율")