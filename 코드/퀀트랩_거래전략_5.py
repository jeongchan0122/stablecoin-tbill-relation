print("데이터 폴더:", 데이터폴더)
print(f"설계: 보유 {주h} 평일, 문헌 호가 차이 3개월 {s3문헌} / 6개월 {s6문헌} bp, 판정 문턱 s* > {판정문턱} bp")

#%% [셀 1] 예측과 금리 읽기 ===================================================
# 4단계 예측 (출처: 퀀트랩_거래전략_4 [셀 5] - 주결과변수(스프레드) h = 13, 큰 모형 = 신호를 넣은 모형)
예측 = pd.read_csv(데이터폴더 / "거래전략_4단계_예측_평일.csv", header=[0, 1], index_col=0, parse_dates=True,
                   encoding=CSV인코딩)
예측 = 예측["주"]["예측_큰"].dropna()

# 금리 (출처: 퀀트랩_BIS_4-1 [셀 2], FRED DGS1MO·DGS3MO·DGS6MO, % -> 소수)
#   휴장일은 채우지 않음 (퀀트랩_BIS_4 [셀 1])
시장 = pd.read_csv(데이터폴더 / "확장_시장자료_원자료_일별.csv", parse_dates=["date"], index_col="date",
                   encoding=CSV인코딩)
평일 = pd.bdate_range(예측.index.min(), 시장.index.max())                 # 평일 달력 (퀀트랩_BIS_2 [셀 0])
금리 = pd.DataFrame({1 / 12: 시장["1개월"], 0.25: 시장["3개월"], 0.5: 시장["6개월"]}).reindex(평일) / 100
print(f"예측: {len(예측)}일 ({예측.index.min().date()} ~ {예측.index.max().date()}), "
      f"예측 < 0 인 날 {int((예측 < 0).sum())}일 ({(예측 < 0).mean():.0%})")


#%% [셀 2] 보유수익률 함수 (설계 "수익률계산") ====================================
def 보간금리(날, 만기):
    """그날 고정만기 금리(1·3·6개월)를 직선 보간해 원하는 만기의 금리를 구함"""
    줄 = 금리.loc[날].dropna()
    if 줄.empty:
        return np.nan
    return float(np.interp(만기, 줄.index.values, 줄.values))


def 보유수익률(산날, 판날, n):
    """로그 보유수익률 R = n·y_n(t) − (n−τ)·y_{n−τ}(t+τ) (Campbell, Lo & MacKinlay 1997 10장)"""
    τ = (판날 - 산날).days / 365
    return n * 금리.at[산날, n] - (n - τ) * 보간금리(판날, n - τ), τ


#%% [셀 3] 날마다의 결정과 성과 =================================================
# 결정하는 날 = 평일 중 4단계 예측이 있는 날 (출처: 설계 "표본외_예측구간")
# 그날 금리가 비어 있으면 6개월물 유지 (출처: 설계 "금리빈날")
날열 = pd.Series(평일, index=평일)
행 = []
for t in 예측.index:
    판날 = 날열.shift(-주h).get(t)
    빔 = pd.isna(판날) or 금리.loc[t, [0.25, 0.5]].isna().any() or 금리.loc[판날].isna().all()
    갈아탐 = (예측[t] < 0) and not 빔                                     # 출처: 설계 "전략규칙"
    R3, τ = 보유수익률(t, 판날, 0.25) if not 빔 else (np.nan, np.nan)
    R6, _ = 보유수익률(t, 판날, 0.5) if not 빔 else (np.nan, np.nan)
    # 비용 계수: 호가 차이 1bp 당 수익률 bp (설계 "비용계산")
    #   3개월물: 살 때 만기 0.25 + 팔 때 남은 만기 0.25−τ / 6개월물: 팔 때 0.5 + 다시 살 때 0.5−τ, 각각 절반
    k3 = (0.25 + (0.25 - τ)) / 2 if not 빔 else np.nan
    k6 = (0.5 + (0.5 - τ)) / 2 if not 빔 else np.nan
    행.append({"date": t, "판날": 판날, "예측_bp": 예측[t], "금리빔": 빔, "갈아탐": 갈아탐, "τ": τ,
              "초과_bp": (R3 - R6) * 1e4, "비용계수3": k3, "비용계수6": k6})
거래 = pd.DataFrame(행).set_index("date")
거래["기여_bp"] = np.where(거래["갈아탐"], 거래["초과_bp"], 0.0)                        # 비용 전
거래["비용_문헌_bp"] = np.where(거래["갈아탐"], s3문헌 * 거래["비용계수3"] + s6문헌 * 거래["비용계수6"], 0.0)
거래.to_csv(데이터폴더 / "거래전략_5단계_거래.csv", encoding=CSV인코딩)

갈 = 거래[거래["갈아탐"]]
print(f"결정한 날 {len(거래)}일, 갈아탄 날 {len(갈)}일 ({len(갈) / len(거래):.0%}), 금리가 비어 유지한 날 {int(거래['금리빔'].sum())}일")
print(f"갈아탄 날 평균: 13일 초과수익 {갈['초과_bp'].mean():+.3f} bp, 문헌값 비용 {갈['비용_문헌_bp'].mean():.3f} bp")


#%% [셀 4] 판정 D: 손익분기 비용 s* ==============================================
# 포트폴리오 = 13 몫, 몫마다 자금 1/13 -> 전체 누적 초과수익 = Σ(갈아탄 날 초과수익) / 13
# s*: 3·6개월물 호가 차이를 같은 s 로 두고 Σ초과 − s × Σ(비용계수3 + 비용계수6) = 0 (설계 "D_손익분기정의")
연수 = (거래["판날"].max() - 거래.index.min()).days / 365
총초과 = 갈["초과_bp"].sum() / 주h
총비용 = 갈["비용_문헌_bp"].sum() / 주h
계수합 = (갈["비용계수3"] + 갈["비용계수6"]).sum()
s별 = 갈["초과_bp"].sum() / 계수합 if 계수합 > 0 else np.nan

# 참고: 날마다 기여의 평균이 0 과 다른가 (NW 시차 h + 4, 판정에 안 씀)
r = sm.OLS(거래["기여_bp"].values, np.ones(len(거래))).fit(cov_type="HAC", cov_kwds={"maxlags": 주h + NW더하기})
# 참고: 신호와 상관없이 매일 갈아탔다면 (3개월물이 그냥 유리했던 기간인지 확인)
늘 = 거래.loc[~거래["금리빔"], "초과_bp"]

판정D = pd.notna(s별) and s별 > 판정문턱
print(f"[판정 D] 기간 {거래.index.min().date()} ~ {거래['판날'].max().date()} ({연수:.2f}년)")
print(f"  누적 초과수익 (자금 전체 기준): 비용 전 {총초과:+.2f} bp, 문헌값 비용 {총비용:.2f} bp, 비용 후 {총초과 - 총비용:+.2f} bp")
print(f"  연 환산: 비용 전 {총초과 / 연수:+.2f} bp/년, 비용 후 {(총초과 - 총비용) / 연수:+.2f} bp/년")
print(f"  손익분기 호가 차이 s* = {s별:.3f} bp  (문턱 {판정문턱} bp)")
print(f"  -> {'성립 (비용을 빼고도 이용 가능)' if 판정D else '성립 안 함'}")
print(f"  [참고] 날마다 기여 평균 {r.params[0]:+.3f} bp, NW t {r.tvalues[0]:+.2f} (판정에 안 씀)")
print(f"  [참고] 신호 무관 매일 갈아탔다면: 13일 초과수익 평균 {늘.mean():+.3f} bp (전체 {len(늘)}일)")

pd.DataFrame([{"기간시작": 거래.index.min().date(), "기간끝": 거래["판날"].max().date(), "연수": 연수,
               "결정일": len(거래), "갈아탄날": len(갈), "누적초과_비용전_bp": 총초과, "문헌비용_bp": 총비용,
               "누적초과_비용후_bp": 총초과 - 총비용, "연초과_비용전_bp": 총초과 / 연수,
               "연초과_비용후_bp": (총초과 - 총비용) / 연수, "손익분기_s_bp": s별, "판정문턱_bp": 판정문턱,
               "판정D": 판정D, "기여평균_t": r.tvalues[0], "매일갈아탐_평균초과_bp": 늘.mean()}]) \
    .to_csv(데이터폴더 / "거래전략_5단계_결과.csv", index=False, encoding=CSV인코딩)
print("저장: 거래전략_5단계_거래.csv, 거래전략_5단계_결과.csv")


