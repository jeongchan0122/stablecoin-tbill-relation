"""
퀀트랩_사건연구_5.py
=====================================================================
[연구] 사건 연구: 미국 스테이블코인법(GENIUS Act)에 대한 주식시장 반응
[단계] 5단계: 사후 분석 - 사건 하나씩 빼 보기 (판정에 안 씀)

[왜 하는가] (3·4단계 결과를 본 뒤 추가 - 사후)
  ① 카드: 사건 C 창(6/12~6/13)에 월스트리트저널의 "월마트·아마존 자체 스테이블코인 검토" 보도(6/13)가 겹침
     -> 카드 결과가 그 보도 하루에 끌려간 것인지 확인
  ② 거래소: 사건 D(상원 통과) 하루가 +22.6% 로 평균의 대부분
     -> 사건 하나에 기댄 결과인지 확인
  두 가지를 같은 규칙으로 보려고, 모든 그룹에서 사건을 하나씩 빼고 주판정값을 다시 계산함

[계산] 3단계와 같음 (주 모형 시장 + IBIT, 추정 기간 250일, 창 [0,+1])
  뺀 뒤 S = 남은 4개 사건의 부호 조정 평균 CAR, 표준오차 = √(남은 창 SE² 합) ÷ 4
[해석 규칙] 판정은 3단계 그대로. 여기 결과는 결론 문장의 강도를 정하는 데만 씀

[입력] 사건연구_설계.csv, 사건연구_3단계_사건별CAR.csv (3단계)
[출력] 사건연구_5단계_사후_사건제외.csv
[Spyder] "#%%" 셀 단위로 Shift+Enter
=====================================================================
"""

#%% [셀 0] 패키지 + 자료 읽기 =============================================
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

데이터폴더 = Path.home() / "Desktop" / "스테이블코인_퀀트랩" / "데이터"
CSV인코딩 = "utf-8-sig"

# 3단계의 사건별 CAR·SE 를 그대로 씀 (같은 모형·같은 창 - 다시 추정하지 않음)
사건표 = pd.read_csv(데이터폴더 / "사건연구_3단계_사건별CAR.csv", encoding=CSV인코딩)
추정기간 = pd.read_csv(데이터폴더 / "사건연구_추정기간.csv", encoding=CSV인코딩).set_index("구분")
자유도 = int(추정기간.loc["주(250일)", "일수"]) - 3            # 3단계와 같음 (계수 3개)
그룹들 = ["발행사", "거래소", "은행", "카드"]
사건들 = list(사건표["사건"].unique())


#%% [셀 1] 사건 하나씩 빼기 ===============================================
def 주판정값(d):
    """설계 "주판정값": 부호 조정 평균 CAR, 창이 겹치지 않으므로 분산을 더함"""
    S = (d["방향"] * d["CAR_%"]).mean()
    SE = np.sqrt((d["SE_%"] ** 2).sum()) / len(d)
    t = S / SE
    return S, SE, t, 2 * stats.t.sf(abs(t), 자유도)


행 = []
for g in 그룹들:
    d = 사건표[사건표["그룹"] == g]
    S, SE, t, p = 주판정값(d)
    행.append({"그룹": g, "뺀사건": "없음 (3단계)", "S_%": S, "SE_%": SE, "t": t, "p": p})
    for e in 사건들:
        S, SE, t, p = 주판정값(d[d["사건"] != e])
        행.append({"그룹": g, "뺀사건": e, "S_%": S, "SE_%": SE, "t": t, "p": p})
결과 = pd.DataFrame(행)

pd.set_option("display.width", 200)
f = lambda v: f"{v:.3f}"
print("[5단계 - 사후] 사건 하나씩 빼고 주판정값 S 다시 계산 (판정에 안 씀)")
for g in 그룹들:
    print(f"\n< {g} >")
    print(결과[결과["그룹"] == g].drop(columns="그룹").to_string(index=False, float_format=f))

# 가장 크게 바뀌는 경우 요약 (사후 해석용)
print("\n요약: 사건 하나를 뺐을 때 p 가 가장 커지는 경우")
for g in 그룹들:
    r = 결과[(결과["그룹"] == g) & (결과["뺀사건"] != "없음 (3단계)")].sort_values("p").iloc[-1]
    print(f"  {g}: {r['뺀사건']} 를 빼면 S {r['S_%']:+.2f}%, p {r['p']:.3f}")


#%% [셀 2] 저장 ===========================================================
결과.to_csv(데이터폴더 / "사건연구_5단계_사후_사건제외.csv", index=False, encoding=CSV인코딩)
print("저장: 사건연구_5단계_사후_사건제외.csv")
